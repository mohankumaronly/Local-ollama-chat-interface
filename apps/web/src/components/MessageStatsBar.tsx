import { Zap, Hash, Clock, Gauge } from 'lucide-react';
import type { MessageStats } from '../types';

function fmt(n: number, digits = 1): string {
  return Number.isFinite(n) ? n.toFixed(digits) : '0';
}

function Stat({
  icon,
  label,
  value,
  title,
}: {
  icon: React.ReactNode;
  label: string;
  value: string;
  title?: string;
}) {
  return (
    <span
      className="flex items-center gap-1 text-[11px] text-gray-400 dark:text-gray-500"
      title={title}
    >
      {icon}
      <span className="font-medium text-gray-500 dark:text-gray-400">{value}</span>
      <span>{label}</span>
    </span>
  );
}

/**
 * Token + performance summary shown under an assistant message.
 * Values come from Ollama's final chunk (prompt_eval_count, eval_count, *_duration).
 */
export function MessageStatsBar({ stats }: { stats: MessageStats }) {
  return (
    <div className="mt-2 flex flex-wrap items-center gap-x-4 gap-y-1 border-t border-gray-200/60 pt-2 dark:border-gray-700/60">
      <Stat
        icon={<Zap size={12} className="text-emerald-500" />}
        value={`${fmt(stats.tokensPerSecond)} tok/s`}
        label="generation"
        title="Generation speed (completion tokens / eval time)"
      />
      <Stat
        icon={<Hash size={12} />}
        value={`${stats.completionTokens}`}
        label="completion tokens"
        title="Tokens generated by the model"
      />
      {stats.promptTokens > 0 && (
        <Stat
          icon={<Hash size={12} />}
          value={`${stats.promptTokens}`}
          label="prompt tokens"
          title="Tokens in the prompt/context that was evaluated"
        />
      )}
      <Stat
        icon={<Gauge size={12} />}
        value={`${stats.totalTokens}`}
        label="total"
        title="Prompt + completion tokens"
      />
      {stats.evalMs > 0 && (
        <Stat
          icon={<Clock size={12} />}
          value={`${fmt(stats.evalMs / 1000, 2)}s`}
          label="gen time"
          title="Time spent generating tokens"
        />
      )}
    </div>
  );
}
